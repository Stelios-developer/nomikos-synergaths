"""Back up and patch only the DMC case-start correlation field in local n8n."""

import json
from pathlib import Path
import subprocess
import sys
import uuid

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from services.backup_crypto import restore_bytes, seal

CONTAINER = "document-rag-n8n"
WORKFLOW = "nexusAgentOrchestrator"


def docker(*args, input=None):
    result = subprocess.run(
        ["docker", *args], input=input, capture_output=True, timeout=60
    )
    if result.returncode:
        raise RuntimeError(
            "The targeted n8n operator command failed; private output withheld"
        )
    return result.stdout


def write_container(path, value):
    code = 'require("fs").writeFileSync(process.argv[1],require("fs").readFileSync(0),{mode:0o600})'
    docker("exec", "-i", CONTAINER, "node", "-e", code, path, input=value)


def main():
    state = docker(
        "exec",
        CONTAINER,
        "node",
        "-e",
        "const {DatabaseSync}=require('node:sqlite'); const d=new DatabaseSync('/home/node/.n8n/database.sqlite',{readOnly:true}); console.log(JSON.stringify(d.prepare(\"SELECT count(*) AS n FROM execution_entity WHERE status IN ('new','running','waiting')\").get())); d.close()",
    )
    if json.loads(state)["n"]:
        raise RuntimeError("n8n has in-flight/waiting work; do not restart it now")
    run_id = uuid.uuid4().hex
    original_path = "/tmp/dmc-original-" + run_id + ".json"
    patched_path = "/tmp/dmc-jobs-" + run_id + ".json"
    changed = False
    original = None
    try:
        docker(
            "exec",
            CONTAINER,
            "n8n",
            "export:workflow",
            "--id=" + WORKFLOW,
            "--output=" + original_path,
        )
        original = docker("exec", CONTAINER, "cat", original_path)
        workflows = json.loads(original)
        if len(workflows) != 1 or workflows[0]["id"] != WORKFLOW:
            raise RuntimeError("Unexpected workflow export scope")
        backup = (
            ROOT / "output/security-backups" / ("n8n-jobs-" + run_id + ".json.aesgcm")
        )
        backup.parent.mkdir(parents=True, exist_ok=True)
        seal(backup, lambda output: output.write(original))
        if restore_bytes(backup) != original:
            raise RuntimeError("Workflow recovery backup did not verify")
        item = workflows[0]
        nodes = [
            node for node in item["nodes"] if node["name"] == "Start document case"
        ]
        if len(nodes) != 1:
            raise RuntimeError("Unexpected case-start node")
        source = json.loads(
            (ROOT / "n8n/agent-orchestrator.workflow.json").read_text(encoding="utf-8")
        )
        desired = next(
            node for node in source["nodes"] if node["name"] == "Start document case"
        )["parameters"]["jsonBody"]
        nodes[0]["parameters"]["jsonBody"] = desired
        required = {
            "saveDataSuccessExecution": "none",
            "saveDataErrorExecution": "none",
            "saveManualExecutions": False,
            "saveExecutionProgress": False,
        }
        if any(
            item.get("settings", {}).get(key) != value
            for key, value in required.items()
        ):
            raise RuntimeError(
                "Retention differs from the reviewed configuration; no setting was changed"
            )
        item["versionId"] = str(uuid.uuid4())
        write_container(patched_path, json.dumps(workflows).encode())
        changed = True
        docker("exec", CONTAINER, "n8n", "import:workflow", "--input=" + patched_path)
        docker("exec", CONTAINER, "n8n", "publish:workflow", "--id=" + WORKFLOW)
        docker("restart", CONTAINER)
        report = {
            "workflow_id": WORKFLOW,
            "gate": "APPLIED",
            "node_changed": "Start document case",
            "encrypted_backup": backup.relative_to(ROOT).as_posix(),
            "unrelated_nodes_replaced": False,
            "payload_retention": "none",
            "restart_performed": True,
        }
        (ROOT / "output/engineering-audit/n8n-job-update.json").write_text(
            json.dumps(report, indent=2) + "\n"
        )
        print(
            "Targeted DMC workflow correlation update published; encrypted recovery backup verified; payload retention preserved as disabled."
        )
    except Exception:
        if changed and original:
            write_container(original_path, original)
            docker(
                "exec", CONTAINER, "n8n", "import:workflow", "--input=" + original_path
            )
            docker("exec", CONTAINER, "n8n", "publish:workflow", "--id=" + WORKFLOW)
            docker("restart", CONTAINER)
        raise
    finally:
        # Exact temporary files generated by this run inside this container only.
        docker("exec", CONTAINER, "rm", "-f", "--", original_path, patched_path)


if __name__ == "__main__":
    main()
